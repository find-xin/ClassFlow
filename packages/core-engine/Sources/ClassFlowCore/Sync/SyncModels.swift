/// Point-in-time state checkpoint generated by a device for rapid bootstrapping and cross-platform synchronization.
public struct DeviceSnapshot: Codable, Sendable, Equatable {
    public var deviceId: String
    public var sequence: Int
    public var courses: [Course]
    public var exceptions: [ScheduleException]
    public var semesters: [Semester]
    public var calendarEvents: [CalendarEvent]
    public var pomodoroTasks: [PomodoroTask]
    public var pomodoroRecords: [PomodoroRecord]
    public var timetableProfiles: [TimetableProfile]
    public var tombstones: [SyncTombstone]

    enum CodingKeys: String, CodingKey {
        case deviceId
        case sequence
        case courses
        case exceptions
        case semesters
        case calendarEvents
        case schedules // Cross-platform compatibility alias for Android
        case pomodoroTasks
        case studyTasks // Cross-platform compatibility alias for Android
        case pomodoroRecords
        case focusRecords // Cross-platform compatibility alias for Android
        case timetableProfiles
        case tombstones
    }

    public init(
        deviceId: String,
        sequence: Int,
        courses: [Course],
        exceptions: [ScheduleException] = [],
        semesters: [Semester] = [],
        calendarEvents: [CalendarEvent] = [],
        pomodoroTasks: [PomodoroTask] = [],
        pomodoroRecords: [PomodoroRecord] = [],
        timetableProfiles: [TimetableProfile] = [],
        tombstones: [SyncTombstone] = []
    ) {
        self.deviceId = deviceId
        self.sequence = sequence
        self.courses = courses
        self.exceptions = exceptions
        self.semesters = semesters
        self.calendarEvents = calendarEvents
        self.pomodoroTasks = pomodoroTasks
        self.pomodoroRecords = pomodoroRecords
        self.timetableProfiles = timetableProfiles
        self.tombstones = tombstones
    }

    public init(from decoder: Decoder) throws {
        let container = try decoder.container(keyedBy: CodingKeys.self)
        self.deviceId = (try? container.decode(String.self, forKey: .deviceId)) ?? "unknown_device"
        self.sequence = (try? container.decodeIfPresent(Int.self, forKey: .sequence)) ?? 0
        self.courses = container.decodeResilientArray(Course.self, forKey: .courses)
        self.exceptions = container.decodeResilientArray(ScheduleException.self, forKey: .exceptions)
        self.semesters = container.decodeResilientArray(Semester.self, forKey: .semesters)
        let evs = container.decodeResilientArray(CalendarEvent.self, forKey: .calendarEvents)
        let scheds = container.decodeResilientArray(CalendarEvent.self, forKey: .schedules)
        self.calendarEvents = !evs.isEmpty ? evs : scheds
        let tasks = container.decodeResilientArray(PomodoroTask.self, forKey: .pomodoroTasks)
        let studyTasks = container.decodeResilientArray(PomodoroTask.self, forKey: .studyTasks)
        self.pomodoroTasks = !tasks.isEmpty ? tasks : studyTasks
        let records = container.decodeResilientArray(PomodoroRecord.self, forKey: .pomodoroRecords)
        let focusRecords = container.decodeResilientArray(PomodoroRecord.self, forKey: .focusRecords)
        self.pomodoroRecords = !records.isEmpty ? records : focusRecords
        self.timetableProfiles = container.decodeResilientArray(TimetableProfile.self, forKey: .timetableProfiles)
        self.tombstones = container.decodeResilientArray(SyncTombstone.self, forKey: .tombstones)
    }

    public func encode(to encoder: Encoder) throws {
        var container = encoder.container(keyedBy: CodingKeys.self)
        try container.encode(deviceId, forKey: .deviceId)
        try container.encode(sequence, forKey: .sequence)
        try container.encode(courses, forKey: .courses)
        try container.encode(exceptions, forKey: .exceptions)
        try container.encode(semesters, forKey: .semesters)
        try container.encode(calendarEvents, forKey: .calendarEvents)
        try container.encode(calendarEvents, forKey: .schedules)
        try container.encode(pomodoroTasks, forKey: .pomodoroTasks)
        try container.encode(pomodoroRecords, forKey: .pomodoroRecords)
        try container.encode(timetableProfiles, forKey: .timetableProfiles)
        try container.encode(tombstones, forKey: .tombstones)
    }
}

/// Helper for resilient element-by-element decoding in distributed snapshots
private struct FailableDecodable<T: Decodable>: Decodable {
    let value: T?
    init(from decoder: Decoder) throws {
        let container = try? decoder.singleValueContainer()
        self.value = try? container?.decode(T.self)
    }
}

private extension KeyedDecodingContainer {
    func decodeResilientArray<T: Decodable>(_ type: T.Type, forKey key: Key) -> [T] {
        if let direct = try? decodeIfPresent([T].self, forKey: key) {
            return direct
        }
        if let failable = try? decodeIfPresent([FailableDecodable<T>].self, forKey: key) {
            return failable.compactMap { $0.value }
        }
        return []
    }
}
